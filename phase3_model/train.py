def _load_one_col_int_csv(path: str) -> np.ndarray:
    """Load a single-column CSV of integers into a numpy array."""
    df = pd.read_csv(path, header=None)
    values = []
    for val in df.iloc[:, 0].tolist():
        s = str(val).strip()
        try:
            values.append(int(s))
        except Exception:
            values.append(int(float(s)))
    return np.asarray(values, dtype=np.int64)


def build_hierarchy_from_data(
    label_path: str,
    family_path: str,
    subcluster_path: str,
    n_classes: int,
) -> tuple[np.ndarray, np.ndarray, np.ndarray, dict]:
    """
    Infer label -> family/subcluster mappings directly from CSV label columns.
    Returns (label_to_family, label_to_subcluster, label_to_family_pos, meta).
    """
    labels = _load_one_col_int_csv(label_path)
    if labels.min() == 1 and labels.max() == n_classes:
        labels = labels - 1
    families = _load_one_col_int_csv(family_path)
    subclusters = _load_one_col_int_csv(subcluster_path)

    if not (len(labels) == len(families) == len(subclusters)):
        raise ValueError("Label, family, and subcluster files must have identical lengths.")

    n_families = int(families.max()) + 1
    n_subclusters = int(subclusters.max()) + 1

    label_to_family = np.zeros((n_classes,), dtype=np.int64)
    label_to_subcluster = np.zeros((n_classes,), dtype=np.int64)
    family_class_indices: list[list[int]] = [[] for _ in range(n_families)]

    for cls_idx in range(n_classes):
        mask = labels == cls_idx
        if not mask.any():
            raise ValueError(f"No samples found for class {cls_idx}.")
        fam_vals = np.unique(families[mask])
        if len(fam_vals) != 1:
            raise ValueError(f"Class {cls_idx} maps to multiple families: {fam_vals}.")
        sub_vals = np.unique(subclusters[mask])
        if len(sub_vals) != 1:
            raise ValueError(f"Class {cls_idx} maps to multiple subclusters: {sub_vals}.")
        fam_id = int(fam_vals[0])
        label_to_family[cls_idx] = fam_id
        label_to_subcluster[cls_idx] = int(sub_vals[0])
        family_class_indices[fam_id].append(cls_idx)

    label_to_family_pos = np.zeros((n_classes,), dtype=np.int64)
    for fam_id, cls_list in enumerate(family_class_indices):
        cls_list.sort()
        for pos, class_idx in enumerate(cls_list):
            label_to_family_pos[class_idx] = pos

    family_subcluster_indices: list[list[int]] = []
    subcluster_to_family = np.full((n_subclusters,), -1, dtype=np.int64)
    subcluster_to_family_pos = np.full((n_subclusters,), -1, dtype=np.int64)
    for fam_id, cls_list in enumerate(family_class_indices):
        subs = sorted({int(label_to_subcluster[idx]) for idx in cls_list})
        family_subcluster_indices.append(subs)
        for pos, sub_id in enumerate(subs):
            subcluster_to_family[sub_id] = fam_id
            subcluster_to_family_pos[sub_id] = pos

    meta = {
        "n_families": n_families,
        "n_subclusters": n_subclusters,
        "family_class_indices": family_class_indices,
        "family_subcluster_indices": family_subcluster_indices,
        "subcluster_to_family": subcluster_to_family,
        "subcluster_to_family_pos": subcluster_to_family_pos,
    }
    return label_to_family, label_to_subcluster, label_to_family_pos, meta

