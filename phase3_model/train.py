def _load_checkpoint(path: str, model: nn.Module, optimizer, scheduler, device: str):
    """
    Loads either:
    - a full checkpoint dict (preferred), or
    - a raw model state_dict (legacy).
    Returns: (start_epoch, best_val_acc, history)
    """
    print(f"\n[Resume] Loading checkpoint from: {path}")
    ckpt = torch.load(path, map_location=device, weights_only=False)

    # Legacy: raw state_dict
    if isinstance(ckpt, dict) and "model_state_dict" not in ckpt and all(isinstance(k, str) for k in ckpt.keys()):
        try:
            model.load_state_dict(ckpt, strict=True)
        except Exception as e:
            print(f"[Resume] Strict load failed (likely architecture changed): {e}")
            missing, unexpected = model.load_state_dict(ckpt, strict=False)
            print(f"[Resume] Loaded with strict=False. Missing keys: {len(missing)}; Unexpected keys: {len(unexpected)}")
        print("[Resume] Loaded legacy model state_dict (no optimizer/scheduler state).")
        return 1, 0.0, {'train_loss': [], 'val_acc': [], 'train_acc': [], 'val_loss': [], 'learning_rates': []}

    try:
        model.load_state_dict(ckpt["model_state_dict"], strict=True)
    except Exception as e:
        print(f"[Resume] Strict load failed (likely architecture changed): {e}")
        missing, unexpected = model.load_state_dict(ckpt["model_state_dict"], strict=False)
        print(f"[Resume] Loaded with strict=False. Missing keys: {len(missing)}; Unexpected keys: {len(unexpected)}")
    if optimizer is not None and "optimizer_state_dict" in ckpt and ckpt["optimizer_state_dict"] is not None:
        optimizer.load_state_dict(ckpt["optimizer_state_dict"])
    if scheduler is not None and "scheduler_state_dict" in ckpt and ckpt["scheduler_state_dict"] is not None:
        scheduler.load_state_dict(ckpt["scheduler_state_dict"])

    start_epoch = int(ckpt.get("epoch", 0)) + 1
    best_val_acc = float(ckpt.get("best_val_acc", 0.0))
    history = ckpt.get("history", {'train_loss': [], 'val_acc': [], 'train_acc': [], 'val_loss': [], 'learning_rates': []})
    print(f"[Resume] Resuming from epoch {start_epoch} (best_val_acc={best_val_acc:.4f})")
    return start_epoch, best_val_acc, history


def _build_scheduler(optimizer):
    scheduler_name = config.get("scheduler", "warmup_cosine")
    total_epochs = int(config["num_epochs"])
    cycle_epochs = int(config.get("scheduler_cycle_epochs", total_epochs))
    cycle_epochs = max(1, min(cycle_epochs, total_epochs))
    warmup_epochs = int(config.get("warmup_epochs", 0))
    warmup_epochs = max(0, min(warmup_epochs, cycle_epochs - 1)) if cycle_epochs > 1 else 0
    lr_min = float(config.get("lr_min", 1e-6))

    if scheduler_name == "warmup_cosine":
        schedulers: list[LinearLR | CosineAnnealingLR | ConstantLR] = []
        milestones: list[int] = []
        elapsed = 0

        if warmup_epochs > 0:
            warmup = LinearLR(
                optimizer,
                start_factor=float(config.get("warmup_start_factor", 1e-2)),
                end_factor=1.0,
                total_iters=warmup_epochs,
            )
            schedulers.append(warmup)
            elapsed += warmup_epochs
            milestones.append(elapsed)

        cosine_iters = max(1, cycle_epochs - warmup_epochs)
        cosine = CosineAnnealingLR(
            optimizer,
            T_max=cosine_iters,
            eta_min=lr_min,
        )
        schedulers.append(cosine)
        elapsed += cosine_iters
        milestones.append(elapsed)

        if elapsed < total_epochs:
            min_factor = lr_min / float(config.get("learning_rate", 1e-3))
            min_factor = max(min_factor, 0.0)
            tail = LambdaLR(optimizer, lr_lambda=lambda _: min_factor)
            schedulers.append(tail)
            milestones.append(total_epochs)

        # SequentialLR expects len(milestones) == len(schedulers) - 1
        return SequentialLR(
            optimizer,
            schedulers=schedulers,
            milestones=milestones[:-1] if len(schedulers) > 1 else [],
        )

    if scheduler_name == "warmup_cosine_restarts":
        warmup = LinearLR(
            optimizer,
            start_factor=float(config.get("warmup_start_factor", 1e-2)),
            end_factor=1.0,
            total_iters=warmup_epochs,
        )
        restarts = CosineAnnealingWarmRestarts(
            optimizer,
            T_0=int(config.get("cosine_t0", 40)),
            T_mult=int(config.get("cosine_t_mult", 2)),
            eta_min=lr_min,
        )
        return SequentialLR(optimizer, schedulers=[warmup, restarts], milestones=[warmup_epochs])

    if scheduler_name == "cosine":
        return CosineAnnealingLR(optimizer, T_max=cycle_epochs, eta_min=lr_min)

    # Fallback: no-op scheduler
    return LambdaLR(optimizer, lr_lambda=lambda _: 1.0)


def _unpack_batch(batch):
    """
    Handles the batch shapes produced by ChromatinDataset under combinations of:
    - use_engineered_features
    - use_hierarchy
    Returns: sequences, engineered_or_None, labels_or_None, fam_or_None, sub_or_None
    """
    use_feat = bool(config.get("use_engineered_features", False))
    use_h = bool(config.get("use_hierarchy", False))

    if use_feat and use_h:
        # (seq, feat, y, fam, sub)
        sequences, engineered, labels, fam, sub = batch
        return sequences, engineered, labels, fam, sub
    if use_feat and not use_h:
        # (seq, feat, y)
        sequences, engineered, labels = batch
        return sequences, engineered, labels, None, None
    if (not use_feat) and use_h:
        # (seq, y, fam, sub)
        sequences, labels, fam, sub = batch
        return sequences, None, labels, fam, sub
    # (seq, y)
    sequences, labels = batch
    return sequences, None, labels, None, None


def _aggregate_ensemble_outputs(output):
    if isinstance(output, dict):
        aggregated = {}
        for key, value in output.items():
            if value is None:
                aggregated[key] = None
            elif isinstance(value, list):
                merged_list = []
                for elem in value:
                    if elem is None:
                        merged_list.append(None)
                    else:
                        merged_list.append(elem.mean(dim=0))
                aggregated[key] = merged_list
            else:
                aggregated[key] = value.mean(dim=0)
        return aggregated
    return output.mean(dim=0)


def train():
    # 0. Hierarchy mapping (optional)
    label_to_family = None
    label_to_subcluster = None
    label_to_family_pos = None
    label_to_family_pos_tensor = None
    subcluster_to_family_pos_tensor = None
    hierarchy_meta = None
    family_class_indices = None
    family_subcluster_indices = None
    if config.get("use_hierarchy", False):
        label_to_family, label_to_subcluster, label_to_family_pos, hierarchy_meta = build_hierarchy_from_data(
            config['train_labels'],
            config['train_family_labels'],
            config['train_subcluster_labels'],
            n_classes=int(config['n_classes'])
        )
        family_class_indices = hierarchy_meta["family_class_indices"]
        family_subcluster_indices = hierarchy_meta["family_subcluster_indices"]
        label_to_family_pos_tensor = torch.from_numpy(label_to_family_pos).to(device, dtype=torch.long)
        subcluster_to_family_pos_tensor = torch.from_numpy(
            hierarchy_meta["subcluster_to_family_pos"]
        ).to(device, dtype=torch.long)
        print("\nHierarchy supervision enabled:")
        print("  source: CSV labels (train split)")
        print(f"  n_families:     {hierarchy_meta['n_families']}")
        print(f"  n_subclusters:  {hierarchy_meta['n_subclusters']}")
        print(f"  family_loss_weight:    {config.get('family_loss_weight', 0.0)}")
        print(f"  subcluster_loss_weight:{config.get('subcluster_loss_weight', 0.0)}")
        if config.get("use_hierarchical_classifier", False):
            print("  hierarchical_classifier: enabled")

    # 1. Setup Data
    train_dataset = ChromatinDataset(
        config['train_sequences'], config['train_labels'],
        family_labels_file=config.get('train_family_labels'),
        subcluster_labels_file=config.get('train_subcluster_labels'),
        jitter_prob=config['jitter_prob'],
        jitter_min_len=config['jitter_min_len'],
        noise_prob=config['noise_prob'],
        cache_data=config['cache_data'],
        use_hierarchy=bool(config.get("use_hierarchy", False)),
        use_engineered_features=bool(config.get("use_engineered_features", False)),
    )
    val_dataset = ChromatinDataset(
        config['val_sequences'], config['val_labels'],
        family_labels_file=config.get('val_family_labels'),
        subcluster_labels_file=config.get('val_subcluster_labels'),
        cache_data=config['cache_data'],
        use_hierarchy=bool(config.get("use_hierarchy", False)),
        use_engineered_features=bool(config.get("use_engineered_features", False)),
    )

    num_workers = int(config.get("num_workers", 0))
    use_pin_memory = (device in ("cuda", "mps"))
    persistent_workers = (num_workers > 0)

    train_loader = DataLoader(
        train_dataset,
        batch_size=config['batch_size'],
        shuffle=True,
        num_workers=num_workers,
        pin_memory=use_pin_memory,
        persistent_workers=persistent_workers,
    )
    val_loader = DataLoader(
        val_dataset,
        batch_size=config['batch_size'],
        shuffle=False,
        num_workers=num_workers,
        pin_memory=use_pin_memory,
        persistent_workers=persistent_workers,
    )

    print("\nDataset sizes:")
    print(f"  train: {len(train_dataset):,}")
    print(f"  val:   {len(val_dataset):,}")

    # 2. Setup Model / Ensemble
    def _create_member():
        return ChromatinCNNAttention(
        n_classes=config['n_classes'],
        use_hierarchy=bool(config.get("use_hierarchy", False)),
        n_families=int(hierarchy_meta["n_families"]) if hierarchy_meta else 0,
        n_subclusters=int(hierarchy_meta["n_subclusters"]) if hierarchy_meta else 0,
        use_engineered_features=bool(config.get("use_engineered_features", False)),
        engineered_feature_dim_in=int(config.get("engineered_feature_dim_in", 5)),
        feature_dim=int(config.get("feature_dim", 128)),
        use_hierarchical_classifier=bool(config.get("use_hierarchical_classifier", False)),
            family_class_indices=family_class_indices,
            family_subcluster_indices=family_subcluster_indices,
            family_embed_dim=int(config.get("family_embed_dim", 0)),
        )

    ensemble_size = max(1, int(config.get("ensemble_size", 1)))
    if ensemble_size > 1:
        members = [_create_member() for _ in range(ensemble_size)]
        model = EnsembleModel(members)
        print(f"\nEnsemble enabled: {ensemble_size} members")
    else:
        model = _create_member()
    model = model.to(device)
    print(f"\nModel: {model.__class__.__name__}")
    print(f"Total parameters: {_count_parameters(model):,}")
    
    # 3. APPLY MI FIX: Data-Driven Initialization
    model.init_filters_from_data(train_loader)
    
    # 4. Optimizer
    optimizer = torch.optim.AdamW(model.parameters(), lr=config['learning_rate'], weight_decay=config['weight_decay'])
    scheduler = _build_scheduler(optimizer)
    criterion = nn.CrossEntropyLoss(label_smoothing=config['label_smoothing'])
    family_criterion = nn.CrossEntropyLoss()
    subcluster_criterion = nn.CrossEntropyLoss()
    
    # 5. Loop
    start_epoch = 1
    best_val_acc = 0.0
    history = {
        'train_loss': [],
        'train_acc': [],
        'val_loss': [],
        'val_acc': [],
        'learning_rates': [],
        'train_ce_loss': [],
        'train_family_loss': [],
        'train_subcluster_loss': [],
        'train_hier_family_loss': [],
        'train_hier_cond_loss': [],
        'val_ce_loss': [],
        'val_family_loss': [],
        'val_subcluster_loss': [],
        'val_hier_family_loss': [],
        'val_hier_cond_loss': [],
    }

    # Resume (optional)
    if config.get("resume_from"):
        start_epoch, best_val_acc, history = _load_checkpoint(
            config["resume_from"], model, optimizer, scheduler, device
        )

    # AMP (CUDA only)
    use_amp = bool(config.get("use_amp", True)) and (device == "cuda")
    scaler = torch.cuda.amp.GradScaler(enabled=use_amp)
    
    print("\nStarting training...")
    print(f"  start_epoch: {start_epoch}")
    print(f"  num_epochs:  {config['num_epochs']}")
    print(f"  scheduler:   {config.get('scheduler')}")
    print(f"  AMP:         {use_amp}")

    patience_counter = 0

    for epoch in range(start_epoch, config['num_epochs'] + 1):
        model.train()
        train_loss = 0.0
        train_ce_loss_total = 0.0
        train_fam_loss_total = 0.0
        train_sub_loss_total = 0.0
        train_hier_family_loss_total = 0.0
        train_hier_cond_loss_total = 0.0
        train_correct = 0
        train_total = 0
        fam_correct = 0
        fam_total = 0
        sub_correct = 0
        sub_total = 0
        
        pbar = tqdm(train_loader, desc=f"Epoch {epoch}")
        for batch in pbar:
            sequences, engineered, labels, fam_labels, sub_labels = _unpack_batch(batch)
            sequences = sequences.to(device)
            labels = labels.to(device)
            engineered = engineered.to(device) if engineered is not None else None
            fam_labels = fam_labels.to(device) if fam_labels is not None else None
            sub_labels = sub_labels.to(device) if sub_labels is not None else None
            
            # Forward
            with torch.autocast(device_type="cuda", dtype=torch.float16, enabled=use_amp):
                out_fwd = model(sequences, engineered=engineered)
                if ensemble_size > 1:
                    out_fwd = _aggregate_ensemble_outputs(out_fwd)
                family_cond_logits = None
                sub_cond_logits = None
                if config.get("use_hierarchy", False):
                    logits = out_fwd["logits_class"]
                    logits_fam = out_fwd["logits_family"]
                    logits_sub = out_fwd["logits_subcluster"]
                    family_cond_logits = out_fwd.get("family_cond_logits")
                    sub_cond_logits = out_fwd.get("sub_cond_logits")
                else:
                    logits = out_fwd
                    logits_fam = None
                    logits_sub = None

                ce_loss = criterion(logits, labels)
                loss = float(config.get("main_ce_weight", 1.0)) * ce_loss

                hier_family_loss = torch.tensor(0.0, device=device)
                hier_cond_loss = torch.tensor(0.0, device=device)
                fam_loss = torch.tensor(0.0, device=device)
                sub_loss = torch.tensor(0.0, device=device)

                if (
                    config.get("use_hierarchical_classifier", False)
                    and family_cond_logits is not None
                    and label_to_family_pos_tensor is not None
                ):
                    fam_pos = label_to_family_pos_tensor[labels]
                    hier_family_loss = family_criterion(logits_fam, fam_labels)
                    cond_loss_sum = torch.tensor(0.0, device=device)
                    cond_count = 0
                    for fam_id, cls_list in enumerate(family_class_indices or []):
                        head_logits = family_cond_logits[fam_id] if family_cond_logits else None
                        if head_logits is None or len(cls_list) == 0:
                            continue
                        mask = (fam_labels == fam_id)
                        if mask.any():
                            cond_loss_sum = cond_loss_sum + criterion(head_logits[mask], fam_pos[mask])
                        cond_count += 1
                    if cond_count > 0:
                        hier_cond_loss = cond_loss_sum / cond_count
                    loss = loss + float(config.get("hier_family_weight", 0.0)) * hier_family_loss
                    loss = loss + float(config.get("hier_cond_weight", 0.0)) * hier_cond_loss
                elif logits_fam is not None and fam_labels is not None:
                    fam_loss = family_criterion(logits_fam, fam_labels)
                    loss = loss + float(config.get("family_loss_weight", 0.0)) * fam_loss

                if config.get("use_hierarchy", False):
                    if sub_cond_logits is not None and subcluster_to_family_pos_tensor is not None:
                        sub_pos = subcluster_to_family_pos_tensor[sub_labels]
                        sub_loss_sum = torch.tensor(0.0, device=device)
                        sub_count = 0
                        for fam_id, sub_ids in enumerate(family_subcluster_indices or []):
                            head_logits = sub_cond_logits[fam_id] if sub_cond_logits else None
                            if head_logits is None or len(sub_ids) == 0:
                                continue
                            mask = (fam_labels == fam_id)
                            if mask.any():
                                sub_loss_sum = sub_loss_sum + subcluster_criterion(head_logits[mask], sub_pos[mask])
                                sub_count += 1
                        if sub_count > 0:
                            sub_loss = sub_loss_sum / sub_count
                            loss = loss + float(config.get("subcluster_loss_weight", 0.0)) * sub_loss
                    elif logits_sub is not None and sub_labels is not None:
                        sub_loss = subcluster_criterion(logits_sub, sub_labels)
                        loss = loss + float(config.get("subcluster_loss_weight", 0.0)) * sub_loss

            optimizer.zero_grad(set_to_none=True)
            scaler.scale(loss).backward()
            torch.nn.utils.clip_grad_norm_(model.parameters(), config['gradient_clip_max_norm'])
            scaler.step(optimizer)
            scaler.update()
            
            train_loss += loss.item()
            train_ce_loss_total += float(ce_loss.detach().item())
            if config.get("use_hierarchy", False):
                if fam_loss is not None:
                    train_fam_loss_total += float(fam_loss.detach().item())
                if sub_loss is not None:
                    train_sub_loss_total += float(sub_loss.detach().item())
            if config.get("use_hierarchical_classifier", False):
                train_hier_family_loss_total += float(hier_family_loss.detach().item())
                train_hier_cond_loss_total += float(hier_cond_loss.detach().item())
            _, pred = torch.max(logits, dim=1)
            train_correct += (pred == labels).sum().item()
            train_total += labels.size(0)

            if config.get("use_hierarchy", False):
                if logits_fam is not None:
                    _, fam_pred = torch.max(logits_fam, dim=1)
                    fam_correct += (fam_pred == fam_labels).sum().item()
                    fam_total += fam_labels.size(0)
                if logits_sub is not None:
                    _, sub_pred = torch.max(logits_sub, dim=1)
                    sub_correct += (sub_pred == sub_labels).sum().item()
                    sub_total += sub_labels.size(0)

            pbar.set_postfix({
                'loss': f"{loss.item():.4f}",
                'lr': f"{optimizer.param_groups[0]['lr']:.2e}",
            })
        
        # Validation
        model.eval()
        val_loss_total = 0.0
        val_ce_loss_total = 0.0
        val_fam_loss_total = 0.0
        val_sub_loss_total = 0.0
        val_hier_family_loss_total = 0.0
        val_hier_cond_loss_total = 0.0
        val_correct = 0
        val_total = 0
        val_fam_correct = 0
        val_fam_total = 0
        val_sub_correct = 0
        val_sub_total = 0
        with torch.no_grad():
            for batch in val_loader:
                sequences, engineered, labels, fam_labels, sub_labels = _unpack_batch(batch)
                sequences = sequences.to(device)
                labels = labels.to(device)
                engineered = engineered.to(device) if engineered is not None else None
                fam_labels = fam_labels.to(device) if fam_labels is not None else None
                sub_labels = sub_labels.to(device) if sub_labels is not None else None

                out = model(sequences, engineered=engineered)
                if ensemble_size > 1:
                    out = _aggregate_ensemble_outputs(out)
                family_cond_logits = None
                sub_cond_logits = None
                if config.get("use_hierarchy", False):
                    logits = out["logits_class"]
                    logits_fam = out["logits_family"]
                    logits_sub = out["logits_subcluster"]
                    family_cond_logits = out.get("family_cond_logits")
                    sub_cond_logits = out.get("sub_cond_logits")
                else:
                    logits = out
                    logits_fam = None
                    logits_sub = None

                ce_loss = criterion(logits, labels)
                val_loss = float(config.get("main_ce_weight", 1.0)) * ce_loss

                hier_family_loss = torch.tensor(0.0, device=device)
                hier_cond_loss = torch.tensor(0.0, device=device)
                fam_loss = torch.tensor(0.0, device=device)
                sub_loss = torch.tensor(0.0, device=device)

                if (
                    config.get("use_hierarchical_classifier", False)
                    and family_cond_logits is not None
                    and label_to_family_pos_tensor is not None
                ):
                    fam_pos = label_to_family_pos_tensor[labels]
                    hier_family_loss = family_criterion(logits_fam, fam_labels)
                    cond_loss_sum = torch.tensor(0.0, device=device)
                    cond_count = 0
                    for fam_id, cls_list in enumerate(family_class_indices or []):
                        head_logits = family_cond_logits[fam_id] if family_cond_logits else None
                        if head_logits is None or len(cls_list) == 0:
                            continue
                        mask = (fam_labels == fam_id)
                        if mask.any():
                            cond_loss_sum = cond_loss_sum + criterion(head_logits[mask], fam_pos[mask])
                            cond_count += 1
                    if cond_count > 0:
                        hier_cond_loss = cond_loss_sum / cond_count
                    val_loss = val_loss + float(config.get("hier_family_weight", 0.0)) * hier_family_loss
                    val_loss = val_loss + float(config.get("hier_cond_weight", 0.0)) * hier_cond_loss
                elif logits_fam is not None and fam_labels is not None:
                    fam_loss = family_criterion(logits_fam, fam_labels)
                    val_loss = val_loss + float(config.get("family_loss_weight", 0.0)) * fam_loss

                if config.get("use_hierarchy", False):
                    if sub_cond_logits is not None and subcluster_to_family_pos_tensor is not None:
                        sub_pos = subcluster_to_family_pos_tensor[sub_labels]
                        sub_loss_sum = torch.tensor(0.0, device=device)
                        sub_count = 0
                        for fam_id, sub_ids in enumerate(family_subcluster_indices or []):
                            head_logits = sub_cond_logits[fam_id] if sub_cond_logits else None
                            if head_logits is None or len(sub_ids) == 0:
                                continue
                            mask = (fam_labels == fam_id)
                            if mask.any():
                                sub_loss_sum = sub_loss_sum + subcluster_criterion(head_logits[mask], sub_pos[mask])
                                sub_count += 1
                        if sub_count > 0:
                            sub_loss = sub_loss_sum / sub_count
                            val_loss = val_loss + float(config.get("subcluster_loss_weight", 0.0)) * sub_loss
                    elif logits_sub is not None and sub_labels is not None:
                        sub_loss = subcluster_criterion(logits_sub, sub_labels)
                        val_loss = val_loss + float(config.get("subcluster_loss_weight", 0.0)) * sub_loss

                val_loss_total += float(val_loss.item())
                val_ce_loss_total += float(ce_loss.detach().item())
                if config.get("use_hierarchy", False):
                    if fam_loss is not None:
                        val_fam_loss_total += float(fam_loss.detach().item())
                    if sub_loss is not None:
                        val_sub_loss_total += float(sub_loss.detach().item())
                if config.get("use_hierarchical_classifier", False):
                    val_hier_family_loss_total += float(hier_family_loss.detach().item())
                    val_hier_cond_loss_total += float(hier_cond_loss.detach().item())

                if config.get("use_hierarchy", False):
                    if logits_fam is not None:
                        _, fam_pred = torch.max(logits_fam, dim=1)
                        val_fam_correct += (fam_pred == fam_labels).sum().item()
                        val_fam_total += fam_labels.size(0)
                    if logits_sub is not None:
                        _, sub_pred = torch.max(logits_sub, dim=1)
                        val_sub_correct += (sub_pred == sub_labels).sum().item()
                        val_sub_total += sub_labels.size(0)

                _, pred = torch.max(logits, dim=1)
                val_correct += (pred == labels).sum().item()
                val_total += labels.size(0)

        val_acc = (val_correct / val_total) if val_total > 0 else 0.0
        train_acc = (train_correct / train_total) if train_total > 0 else 0.0
        train_fam_acc = (fam_correct / fam_total) if fam_total > 0 else 0.0
        train_sub_acc = (sub_correct / sub_total) if sub_total > 0 else 0.0
        val_fam_acc = (val_fam_correct / val_fam_total) if val_fam_total > 0 else 0.0
        val_sub_acc = (val_sub_correct / val_sub_total) if val_sub_total > 0 else 0.0
        train_loss_avg = train_loss / len(train_loader)
        train_ce_loss_avg = train_ce_loss_total / len(train_loader)
        train_fam_loss_avg = train_fam_loss_total / len(train_loader)
        train_sub_loss_avg = train_sub_loss_total / len(train_loader)
        train_hier_family_loss_avg = train_hier_family_loss_total / len(train_loader)
        train_hier_cond_loss_avg = train_hier_cond_loss_total / len(train_loader)
        val_loss_avg = val_loss_total / len(val_loader)
        val_ce_loss_avg = val_ce_loss_total / len(val_loader)
        val_fam_loss_avg = val_fam_loss_total / len(val_loader)
        val_sub_loss_avg = val_sub_loss_total / len(val_loader)
        val_hier_family_loss_avg = val_hier_family_loss_total / len(val_loader)
        val_hier_cond_loss_avg = val_hier_cond_loss_total / len(val_loader)

        # Step scheduler AFTER validation to keep reporting aligned with epoch summary.
        scheduler.step()
        current_lr = optimizer.param_groups[0]['lr']

        history['train_loss'].append(train_loss_avg)
        history['train_acc'].append(train_acc)
        history['val_loss'].append(val_loss_avg)
        history['val_acc'].append(val_acc)
        history['learning_rates'].append(current_lr)
        history['train_ce_loss'].append(train_ce_loss_avg)
        history['train_family_loss'].append(train_fam_loss_avg)
        history['train_subcluster_loss'].append(train_sub_loss_avg)
        history['train_hier_family_loss'].append(train_hier_family_loss_avg)
        history['train_hier_cond_loss'].append(train_hier_cond_loss_avg)
        history['val_ce_loss'].append(val_ce_loss_avg)
        history['val_family_loss'].append(val_fam_loss_avg)
        history['val_subcluster_loss'].append(val_sub_loss_avg)
        history['val_hier_family_loss'].append(val_hier_family_loss_avg)
        history['val_hier_cond_loss'].append(val_hier_cond_loss_avg)

        print(
            f"Epoch {epoch:03d} | "
            f"LR: {current_lr:.2e} | "
            f"Train Loss: {train_loss_avg:.4f} [CE {train_ce_loss_avg:.4f}, hier_f {train_hier_family_loss_avg:.3f}, hier_c {train_hier_cond_loss_avg:.3f}, fam {train_fam_loss_avg:.3f}, sub {train_sub_loss_avg:.3f}] | "
            f"Val Loss: {val_loss_avg:.4f} [CE {val_ce_loss_avg:.4f}, hier_f {val_hier_family_loss_avg:.3f}, hier_c {val_hier_cond_loss_avg:.3f}, fam {val_fam_loss_avg:.3f}, sub {val_sub_loss_avg:.3f}] | "
            f"Val Acc: {val_acc:.4f}"
        )
        if config.get("use_hierarchy", False):
            print(
                f"           Aux | "
                f"Train fam: {train_fam_acc:.3f} sub: {train_sub_acc:.3f} | "
                f"Val fam: {val_fam_acc:.3f} sub: {val_sub_acc:.3f}"
            )
        
        if val_acc > best_val_acc:
            best_val_acc = val_acc
            best_path = os.path.join(CHECKPOINT_DIR, 'best_model_improved.pt')
            _save_checkpoint(best_path, model, optimizer, scheduler, epoch, best_val_acc, history)
            print(f"--> New Best Checkpoint Saved (Acc: {best_val_acc:.4f})")
            patience_counter = 0
        else:
            patience_counter += 1

        # Rolling checkpoint (for resume safety)
        save_every = int(config.get("save_every_epochs", 0) or 0)
        if save_every > 0 and (epoch % save_every == 0):
            last_path = os.path.join(CHECKPOINT_DIR, 'checkpoint_last.pt')
            _save_checkpoint(last_path, model, optimizer, scheduler, epoch, best_val_acc, history)
            print(f"--> Saved rolling checkpoint: checkpoint_last.pt (epoch {epoch})")

        # Early stopping
        if patience_counter >= int(config.get("early_stopping_patience", 30)):
            print(f"Early stopping: no improvement for {patience_counter} epoch(s).")
            break
            
    print("Training Complete.")
    
    # Save History
    with open(os.path.join(CHECKPOINT_DIR, 'history.json'), 'w') as f:
        json.dump(history, f)


if __name__ == "__main__":
    train()
