def one_hot_encode(sequence: str) -> np.ndarray:
    """Convert DNA sequence to one-hot encoded array."""
    base_to_idx = {'A': 0, 'C': 1, 'G': 2, 'T': 3}
    one_hot = np.zeros((200, 4), dtype=np.float32)
    for i, base in enumerate(sequence):
        if base in base_to_idx:
            one_hot[i, base_to_idx[base]] = 1.0
        else:
            one_hot[i, :] = 0.25
    return one_hot


def compute_engineered_features(sequence: str) -> np.ndarray:
    """
    Lightweight engineered features (5 dims), aligned with Phase8 diagnostics:
    - gc_content: fraction of G/C
    - cpg_ratio: observed/expected CpG (protect against 0)
    - entropy: Shannon entropy of base frequencies
    - max_run_len: longest homopolymer run length
    - repeat_density: fraction of positions belonging to runs >= 3
    """
    s = sequence.upper()
    n = len(s) if len(s) > 0 else 1

    # Base counts
    a = s.count("A")
    c = s.count("C")
    g = s.count("G")
    t = s.count("T")
    total = a + c + g + t
    if total == 0:
        # unknown sequence: neutral defaults
        return np.array([0.5, 1.0, 2.0, 1.0, 0.0], dtype=np.float32)

    gc_content = (g + c) / total

    # CpG observed/expected
    cpg_obs = sum(1 for i in range(len(s) - 1) if s[i] == "C" and s[i + 1] == "G")
    c_freq = c / total
    g_freq = g / total
    cpg_exp = max(1e-8, (len(s) - 1) * c_freq * g_freq)
    cpg_ratio = float(cpg_obs) / float(cpg_exp)

    # Entropy (base distribution)
    p = np.array([a, c, g, t], dtype=np.float32) / float(total)
    entropy = float(-(p[p > 0] * np.log(p[p > 0])).sum())

    # Runs
    max_run = 1
    repeat_positions = 0
    run_len = 1
    for i in range(1, len(s)):
        if s[i] == s[i - 1] and s[i] in "ACGT":
            run_len += 1
        else:
            max_run = max(max_run, run_len)
            if run_len >= 3:
                repeat_positions += run_len
            run_len = 1
    max_run = max(max_run, run_len)
    if run_len >= 3:
        repeat_positions += run_len

    repeat_density = repeat_positions / max(1, len(s))

    return np.array([gc_content, cpg_ratio, entropy, float(max_run), repeat_density], dtype=np.float32)

class ChromatinDataset(Dataset):
    def __init__(self, sequences_file, labels_file=None,
                 family_labels_file=None, subcluster_labels_file=None,
                 jitter_prob=0.0, jitter_min_len=180, noise_prob=0.0, 
                 sequence_length=200, cache_data=True,
                 use_hierarchy: bool = False,
                 **kwargs):
        self.sequences_file = Path(sequences_file)
        self.labels_file = Path(labels_file) if labels_file else None
        self.jitter_prob = jitter_prob
        self.jitter_min_len = jitter_min_len
        self.noise_prob = noise_prob
        self.sequence_length = sequence_length
        self.use_hierarchy = use_hierarchy
        
        print(f"Loading sequences from {self.sequences_file}")
        sequences_df = pd.read_csv(self.sequences_file, header=None)
        self.sequences = sequences_df.iloc[:, 1].values if sequences_df.shape[1] > 1 else sequences_df[0].values
        
        self.labels = None
        if self.labels_file:
            print(f"Loading labels from {self.labels_file}")
            labels_df = pd.read_csv(self.labels_file, header=None)
            self.labels = labels_df.iloc[:, 1].values if labels_df.shape[1] > 1 else labels_df[0].values
            self.labels = self.labels - 1 # 1-18 -> 0-17

        self.family_labels = None
        self.subcluster_labels = None
        if self.use_hierarchy:
            if family_labels_file is None or subcluster_labels_file is None:
                raise ValueError("use_hierarchy=True requires family and subcluster label files.")
            fam_arr = _load_one_col_int_csv(family_labels_file)
            sub_arr = _load_one_col_int_csv(subcluster_labels_file)
            if len(fam_arr) != len(self.sequences) or len(sub_arr) != len(self.sequences):
                raise ValueError("Family/subcluster label lengths must match sequences.")
            self.family_labels = fam_arr
            self.subcluster_labels = sub_arr

        self._cached_sequences = None
        self._cached_features = None
        if cache_data:
            print("Caching one-hot encodings...")
            self._cached_sequences = [one_hot_encode(seq) for seq in self.sequences]
            if kwargs.get("use_engineered_features", True) or config.get("use_engineered_features", False):
                print("Caching engineered features...")
                self._cached_features = [compute_engineered_features(seq) for seq in self.sequences]

    def __len__(self):
        return len(self.sequences)

    def __getitem__(self, idx):
        # 1. Get Sequence
        if self._cached_sequences:
            sequence = self._cached_sequences[idx].copy()
        else:
            sequence = one_hot_encode(self.sequences[idx])

        # Engineered features
        engineered = None
        if config.get("use_engineered_features", False):
            if self._cached_features is not None:
                engineered = self._cached_features[idx].copy()
            else:
                engineered = compute_engineered_features(self.sequences[idx])

        # 2. Augmentations
        if self.jitter_prob > 0 and random.random() < self.jitter_prob:
            crop_len = random.randint(self.jitter_min_len, self.sequence_length)
            start_pos = random.randint(0, self.sequence_length - crop_len)
            cropped = sequence[start_pos:start_pos+crop_len, :].copy()
            sequence = np.zeros_like(sequence)
            sequence[:cropped.shape[0], :] = cropped

        if self.noise_prob > 0:
            noise_mask = np.random.random((self.sequence_length, 4)) < self.noise_prob
            noise_seq = np.random.random((self.sequence_length, 4)).astype(np.float32)
            noise_seq /= noise_seq.sum(axis=1, keepdims=True)
            sequence[noise_mask] = noise_seq[noise_mask]

        sequence_tensor = torch.from_numpy(sequence).float()
        engineered_tensor = torch.from_numpy(engineered).float() if engineered is not None else None
        
        # Return tuple (sequence[, engineered], label[, family, subcluster])
        if self.labels is not None:
            y = int(self.labels[idx])
            if self.use_hierarchy:
                if self.family_labels is None or self.subcluster_labels is None:
                    raise ValueError("Hierarchy labels were not loaded.")
                fam = int(self.family_labels[idx])
                sub = int(self.subcluster_labels[idx])
                if engineered_tensor is not None:
                    return (
                        sequence_tensor,
                        engineered_tensor,
                        torch.tensor(y, dtype=torch.long),
                        torch.tensor(fam, dtype=torch.long),
                        torch.tensor(sub, dtype=torch.long),
                    )
                return (
                    sequence_tensor,
                    torch.tensor(y, dtype=torch.long),
                    torch.tensor(fam, dtype=torch.long),
                    torch.tensor(sub, dtype=torch.long),
                )
            if engineered_tensor is not None:
                return sequence_tensor, engineered_tensor, torch.tensor(y, dtype=torch.long)
            return sequence_tensor, torch.tensor(y, dtype=torch.long)

        if engineered_tensor is not None:
            return sequence_tensor, engineered_tensor
        return sequence_tensor

